// Generates src/core/colors/tailwindPalette.ts from the installed Tailwind theme (node_modules/tailwindcss/theme.css).
// Usage: node scripts/generate-palette.mjs
// The theme stores colours as oklch(); they are converted to sRGB (CSS Color 4, clipped to gamut) and written as #rrggbb.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const themePath = join(root, 'node_modules/tailwindcss/theme.css')
const outPath = join(root, 'src/core/colors/tailwindPalette.ts')

/** The classic 22 hues of Tailwind's palette; the newer v4 neutrals (mauve, mist, olive, taupe) are left out. */
const HUES = [
  'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue',
  'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose', 'slate', 'gray', 'zinc', 'neutral', 'stone'
]
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

function oklchToHex(l, c, hDeg) {
  const h = (hDeg * Math.PI) / 180
  const a = c * Math.cos(h)
  const b = c * Math.sin(h)
  const l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s_ = (l - 0.0894841775 * a - 1.291485548 * b) ** 3
  const lin = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_
  ]
  const encode = (x) => {
    const v = Math.min(1, Math.max(0, x))
    return v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055
  }
  return '#' + lin.map((x) => Math.round(encode(x) * 255).toString(16).padStart(2, '0')).join('')
}

const css = readFileSync(themePath, 'utf8')
const oklch = new Map()
for (const m of css.matchAll(/--color-([a-z]+)-(\d+):\s*oklch\(([\d.]+)% ([\d.]+) ([\d.]+|none)\);/g)) {
  // "none" is an achromatic hue; its chroma is 0, so the hue does not matter.
  oklch.set(`${m[1]}-${m[2]}`, [Number(m[3]) / 100, Number(m[4]), m[5] === 'none' ? 0 : Number(m[5])])
}
const hex = (name) => {
  const v = oklch.get(name)
  if (!v) throw new Error(`missing --color-${name} in ${themePath}`)
  return oklchToHex(...v)
}

const rows = HUES.map((hue) => {
  const hexes = SHADES.map((shade) => hex(`${hue}-${shade}`))
  return `  { hue: '${hue}', hexes: [${hexes.map((x) => `'${x}'`).join(', ')}] }`
})
const black = css.match(/--color-black:\s*(#[0-9a-fA-F]{3,6});/)?.[1]
const white = css.match(/--color-white:\s*(#[0-9a-fA-F]{3,6});/)?.[1]
if (!black || !white) throw new Error('black or white missing in theme')

const source = `// Generated by scripts/generate-palette.mjs from node_modules/tailwindcss/theme.css. Do not edit by hand.
export const TAILWIND_SHADES = [${SHADES.join(', ')}] as const

/** One row per hue; hexes are in the order of TAILWIND_SHADES. */
export const TAILWIND_ROWS: readonly { hue: string; hexes: readonly string[] }[] = [
${rows.join(',\n')}
]

export const TAILWIND_NEUTRALS: readonly { name: 'white' | 'black'; hex: string }[] = [
  { name: 'white', hex: '${white.length === 4 ? '#' + [...white.slice(1)].map((c) => c + c).join('') : white.toLowerCase()}' },
  { name: 'black', hex: '${black.length === 4 ? '#' + [...black.slice(1)].map((c) => c + c).join('') : black.toLowerCase()}' }
]
`
writeFileSync(outPath, source)
console.log(`wrote ${outPath} (${HUES.length} hues x ${SHADES.length} shades + white, black)`)
