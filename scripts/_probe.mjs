import { chromium } from 'playwright-core'
import { createServer } from 'vite'
import { readdirSync } from 'node:fs'
const root = '/opt/pw-browsers'
const dir = readdirSync(root).find((d) => d.startsWith('chromium-'))
const server = await createServer({ server: { port: 5192, strictPort: true }, logLevel: 'error' })
await server.listen()
const browser = await chromium.launch({ executablePath: `${root}/${dir}/chrome-linux/chrome`, args: ['--no-sandbox'] })
const page = await (await browser.newContext({ locale: 'en-US', viewport: { width: 1120, height: 700 } })).newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
await page.goto('http://localhost:5192/app')
await page.getByRole('button', { name: 'Clip: Beach.mp4', exact: true }).first().waitFor()
const vol = () => page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia.state.value.editor.history.present.clips.find((c) => c.id === 'clip-beach').volume)
await page.getByRole('button', { name: 'Clip: Beach.mp4', exact: true }).first().click()
const zoom = page.locator('aside').getByRole('slider', { name: 'Zoom' })
let zb = await zoom.boundingBox()
await page.mouse.move(zb.x + zb.width * 0.5, zb.y + zb.height / 2); await page.mouse.down()
await page.mouse.move(zb.x + zb.width * 0.9, zb.y + zb.height / 2, { steps: 10 }); await page.mouse.up()
console.log('zoom after drag', await zoom.inputValue())
await page.keyboard.press('Control+z')
console.log('zoom after undo', await zoom.inputValue(), 'vol', await vol())
const slider = page.locator('aside').getByRole('slider', { name: 'Volume' })
console.log('count', await slider.count(), 'value', await slider.inputValue(), 'valuetext', await slider.getAttribute('aria-valuetext'))
const box = await slider.boundingBox()
console.log('box', JSON.stringify(box))
await page.mouse.move(box.x + box.width * 0.5, box.y + box.height / 2)
await page.mouse.down()
await page.mouse.move(box.x + box.width * 0.8, box.y + box.height / 2, { steps: 10 })
await page.mouse.up()
console.log('after mouse drag vol', await vol(), 'input', await slider.inputValue())
await browser.close(); await server.close()
